#!/usr/bin/env python3
"""从 spec/ 生成各语言的常量文件，避免两端手抄提示词与预设。

生成物：
    macos/Sources/AITransCore/Generated/Spec.swift
    windows/AITrans.Core/Generated/Spec.cs   （存在 windows/ 时）

CI 会重新生成并检查 git diff，确保 spec/ 与代码一致。

用法：
    python3 tools/gen_spec.py          # 生成
    python3 tools/gen_spec.py --check  # 只检查是否最新
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "spec"

SWIFT_OUT = ROOT / "Sources" / "TransCore" / "Generated" / "Spec.swift"


# ---------------------------------------------------------------- helpers

def load(name: str) -> dict:
    return json.loads((SPEC / name).read_text(encoding="utf-8"))


def swift_string(value: str, indent: str = "    ") -> str:
    """优先用 Swift 原始字符串，避免转义提示词里的引号与反斜杠。"""
    if "\n" in value:
        if '"""#' in value:
            raise ValueError("内容里出现了 Swift 原始字符串的结束标记")
        body = "\n".join(indent + line if line else "" for line in value.split("\n"))
        return f'#"""\n{body}\n{indent}"""#'
    if '"#' in value:
        raise ValueError("内容里出现了 Swift 原始字符串的结束标记")
    return f'#"{value}"#'


def csharp_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )
    return f'"{escaped}"'


# ---------------------------------------------------------------- swift

SWIFT_HEADER = """// Generated by tools/gen_spec.py — do not edit by hand.
// Source of truth: spec/*.json
import Foundation

public enum Spec {
    public static let version = {version}
"""


def render_swift(prompts: dict, presets: dict, parsing: dict) -> str:
    langs = prompts["languages"]
    lang_lines = "\n".join(
        f'        {swift_string(k)}: {swift_string(v)},' for k, v in langs.items()
    )

    preset_lines = []
    for preset in presets["presets"]:
        preset_lines.append(
            "        ProviderPreset(\n"
            f'            id: {swift_string(preset["id"])},\n'
            f'            name: {swift_string(preset["name"])},\n'
            f'            baseURL: {swift_string(preset["base_url"])},\n'
            f'            model: {swift_string(preset["model"])},\n'
            f'            requiresKey: {"true" if preset["requires_key"] else "false"}\n'
            "        ),"
        )
    preset_block = "\n".join(preset_lines)

    patterns = ",\n".join(
        f"        {swift_string(p)}" for p in parsing["batchResultPatterns"]
    )

    retry = parsing["retry"]
    thinking = parsing["thinking"]

    return (
        SWIFT_HEADER.replace("{version}", str(parsing["version"]))
        + f"""
    // MARK: - 语言

    public static let languages: [String: String] = [
{lang_lines}
    ]

    // MARK: - 提示词

    public static let translateSystemPrompt = {swift_string(prompts["translate"]["system"])}
    public static let translateUserTemplate = {swift_string(prompts["translate"]["user"])}
    public static let polishSystemPrompt = {swift_string(prompts["polish"]["system"])}
    public static let polishUserWithContext = {swift_string(prompts["polish"]["userWithContext"])}
    public static let polishUserWithoutContext = {swift_string(prompts["polish"]["userWithoutContext"])}
    public static let polishNumberedLine = {swift_string(prompts["polish"]["numberedLine"])}

    // MARK: - 提供商预设

    public static let presets: [ProviderPreset] = [
{preset_block}
    ]

    // MARK: - 解析规则

    public static let blockSplitPattern = {swift_string(parsing["blockSplitRegex"])}
    public static let minLinesForValidBlock = {parsing["minLinesForValidBlock"]}
    public static let quoteStripPattern = {swift_string(parsing["quoteStripRegex"])}
    public static let blockSeparator = {swift_string(parsing["blockSeparator"])}
    public static let batchResultPatterns: [String] = [
{patterns}
    ]

    // MARK: - 默认值

    public static let defaultTranslateWorkers = {parsing["translate"]["defaultWorkers"]}
    public static let defaultTimeoutSeconds = {parsing["translate"]["defaultTimeoutSeconds"]}
    public static let defaultRetries = {parsing["translate"]["defaultRetries"]}
    public static let defaultPolishBatchSize = {parsing["polish"]["defaultBatchSize"]}
    public static let defaultPolishWorkers = {parsing["polish"]["defaultWorkers"]}
    public static let polishContextBatches = {parsing["polish"]["contextBatches"]}

    // MARK: - 重试

    public static let retryDelayBaseSeconds = {retry["delayBaseSeconds"]}
    public static let retryableHTTPStatuses: Set<Int> = [{", ".join(str(s) for s in retry["retryableHttpStatuses"])}]
    public static let retryableHTTPStatusAtLeast = {retry["retryableHttpStatusAtLeast"]}

    // MARK: - 思考模式

    public static let thinkingHostKeyword = {swift_string(thinking["defaultWhenHostContains"])}
    public static let thinkingOverrideEnvVar = {swift_string(thinking["overrideEnvVar"])}
}}
"""
    )


# ---------------------------------------------------------------- csharp

CSHARP_HEADER = """// Generated by tools/gen_spec.py — do not edit by hand.
// Source of truth: spec/*.json
namespace AITrans.Core;

public static class Spec
{
    public const int Version = {version};
"""


def render_csharp(prompts: dict, presets: dict, parsing: dict) -> str:
    langs = "\n".join(
        f"        [{csharp_string(k)}] = {csharp_string(v)},"
        for k, v in prompts["languages"].items()
    )

    preset_lines = []
    for preset in presets["presets"]:
        preset_lines.append(
            "        new ProviderPreset(\n"
            f"            Id: {csharp_string(preset['id'])},\n"
            f"            Name: {csharp_string(preset['name'])},\n"
            f"            BaseUrl: {csharp_string(preset['base_url'])},\n"
            f"            Model: {csharp_string(preset['model'])},\n"
            f"            RequiresKey: {'true' if preset['requires_key'] else 'false'}),"
        )
    preset_block = "\n".join(preset_lines)

    patterns = ",\n".join(f"        {csharp_string(p)}" for p in parsing["batchResultPatterns"])
    retry = parsing["retry"]
    thinking = parsing["thinking"]

    return (
        CSHARP_HEADER.replace("{version}", str(parsing["version"]))
        + f"""
    public static readonly IReadOnlyDictionary<string, string> Languages = new Dictionary<string, string>
    {{
{langs}
    }};

    public const string TranslateSystemPrompt = {csharp_string(prompts["translate"]["system"])};
    public const string TranslateUserTemplate = {csharp_string(prompts["translate"]["user"])};
    public const string PolishSystemPrompt = {csharp_string(prompts["polish"]["system"])};
    public const string PolishUserWithContext = {csharp_string(prompts["polish"]["userWithContext"])};
    public const string PolishUserWithoutContext = {csharp_string(prompts["polish"]["userWithoutContext"])};
    public const string PolishNumberedLine = {csharp_string(prompts["polish"]["numberedLine"])};

    public static readonly ProviderPreset[] Presets =
    {{
{preset_block}
    }};

    public const string BlockSplitPattern = {csharp_string(parsing["blockSplitRegex"])};
    public const int MinLinesForValidBlock = {parsing["minLinesForValidBlock"]};
    public const string QuoteStripPattern = {csharp_string(parsing["quoteStripRegex"])};
    public const string BlockSeparator = {csharp_string(parsing["blockSeparator"])};

    public static readonly string[] BatchResultPatterns =
    {{
{patterns}
    }};

    public const int DefaultTranslateWorkers = {parsing["translate"]["defaultWorkers"]};
    public const int DefaultTimeoutSeconds = {parsing["translate"]["defaultTimeoutSeconds"]};
    public const int DefaultRetries = {parsing["translate"]["defaultRetries"]};
    public const int DefaultPolishBatchSize = {parsing["polish"]["defaultBatchSize"]};
    public const int DefaultPolishWorkers = {parsing["polish"]["defaultWorkers"]};
    public const int PolishContextBatches = {parsing["polish"]["contextBatches"]};

    public const int RetryDelayBaseSeconds = {retry["delayBaseSeconds"]};
    public static readonly int[] RetryableHttpStatuses = {{ {", ".join(str(s) for s in retry["retryableHttpStatuses"])} }};
    public const int RetryableHttpStatusAtLeast = {retry["retryableHttpStatusAtLeast"]};

    public const string ThinkingHostKeyword = {csharp_string(thinking["defaultWhenHostContains"])};
    public const string ThinkingOverrideEnvVar = {csharp_string(thinking["overrideEnvVar"])};
}}
"""
    )


# ---------------------------------------------------------------- main

def main(argv: list[str]) -> int:
    check = "--check" in argv
    prompts = load("prompts/prompts.json")
    presets = load("providers.presets.json")
    parsing = load("parsing.json")

    outputs = {SWIFT_OUT: render_swift(prompts, presets, parsing)}

    stale = []
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            print(f"unchanged {path.relative_to(ROOT)}")
            continue
        if check:
            stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")

    if check and stale:
        for path in stale:
            print(f"OUT OF DATE: {path.relative_to(ROOT)}", file=sys.stderr)
        print("run: python3 tools/gen_spec.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
